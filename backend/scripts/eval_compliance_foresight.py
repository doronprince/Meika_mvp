"""Measures tax & compliance foresight instead of asserting it works.

    cd backend
    python -m scripts.eval_compliance_foresight
    python -m scripts.eval_compliance_foresight --ledgers 100 --json ../figures/compliance_eval.json

Runs in-process against the production detectors and engine (no database,
no network), so every number is reproducible from the seed alone.

CORPUS. N seeded synthetic ledgers of 540 days (18 months) each: rent paid
on a fixed day, groceries, education instalments per semester, monthly
transfers home (half the ledgers log them in USD), an occasional one-off
large transfer, trips abroad in JPY/EUR/USD, and a random share of education
and housing costs marked as having a receipt. Amounts carry lognormal noise
(sigma 0.4) so rates are genuinely uncertain. Per-ledger intensities are
drawn around each rule's assumed figure, so some ledgers cross and some
don't.

GROUND TRUTH IS DEFINITIONAL, NOT ANNOTATED. For each (ledger, threshold
rule) the crossing date is the first day the rule's own observable — a
rolling-12-month or tax-year-to-date sum, or one transaction — reaches the
assumed figure, found by daily replay. The engine is replayed at day 7, 14,
21 and then weekly, with `today` set to each checkpoint; it sees only the past.

WHAT IS MEASURED (threshold rules only; the two pattern rules have no
crossing to be early about, so only their emission rates are reported):
  1. Lead time vs the threshold-only baseline (which fires on the crossing
     day, lead 0 by construction).
  2. False alarms on pairs that never cross, judged only where the flag's
     claim window lies fully inside the data.
  3. Claim precision: of MODERATE flags ("reaches it before the tax year
     ends"), how many were right.
  4. Band sweep, and the selection rule fixed before looking: ship the
     LARGEST watch multiplier whose LOW-or-above false-alarm rate is <= 0.10,
     and the SMALLEST early-ledger ratio meeting the same bar. If no value
     meets it, ship the most conservative value in the grid (no watch band;
     no early flag) and report that the target was not met. The fallback
     band is chosen the same way against the MODERATE false-alarm rate.
  5. Interval coverage of [earliest, latest], by how the range was built.
     No nominal coverage is claimed; the observed number is the result.
  6. Cold-start gates: zero projections below 30 days of history and zero
     watch-band flags below 90 (a hard check — the script fails otherwise).
  7. Explanation sufficiency: severity recomputed from the published flag
     fields alone.
  8. Safety lint: assertive-law phrases over every generated string, and
     referral presence on every flag.
  9. Determinism and latency.
 10. Sensitivity of flag counts and lead time to each assumed figure (x0.5 to x1.5).

NOT MEASURED, AND WHY: the design's comprehension study (do users read a flag
as legal fact?) needs human participants and is not faked here. All numbers
are synthetic, generated by the same author who wrote the detectors — they
show how the detectors behave under known dynamics, not accuracy on real
users, and they validate the detectors, not the assumed figures.
"""

